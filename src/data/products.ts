export function getOrderedProducts(products: Product[], onlyFeatured = false): Product[] {
  const list = onlyFeatured ? products.filter((p) => p.isFeatured !== false) : products;
  return [...list].sort((a, b) => (a.displayOrder ?? 999) - (b.displayOrder ?? 999));
}
